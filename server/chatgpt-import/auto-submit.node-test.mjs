import test from "node:test";
import assert from "node:assert/strict";
import sharp from "sharp";
import { autoSubmitGeneratedImage } from "./auto-submit.mjs";

const token="B".repeat(48);
const root="https://nanal.example";
const HASH="a".repeat(64),PORTRAIT="b".repeat(64),BODY="c".repeat(64);
const profile={appearanceId:"AP008",source:"reviewed_official_reservation",
  profileSha256:HASH,portraitAnchorSha256:PORTRAIT,fullBodyAnchorSha256:BODY};
async function image(slot,mode="transparent") {
 const w=1024,h=slot==="portrait"?1024:1536;
 const pixels=Buffer.alloc(w*h*4);
 for(let y=180;y<h-180;y++)for(let x=210;x<w-210;x++) {
   const i=(y*w+x)*4;
   pixels[i]=mode==="magenta"?255:96;
   pixels[i+1]=mode==="magenta"?0:105;
   pixels[i+2]=mode==="magenta"?255:125;
   pixels[i+3]=255;
 }
 if(mode==="opaque")for(let i=3;i<pixels.length;i+=4)pixels[i]=255;
 return sharp(pixels,{raw:{width:w,height:h,channels:4}}).png().toBuffer();
}
function stub(override={}) {
 const calls=[];
 const fetcher=async(url,opt={})=>{
   calls.push({url,method:opt.method||"GET"});
   if(url.endsWith("/AP008")&&!opt.method) return Response.json(override.profile||profile,{status:override.getStatus||200});
   if(url.endsWith("/AP008/variants")) {
     const form=opt.body;
     assert.equal(opt.headers.Authorization,"Bearer "+token);
     assert.equal(form.get("slot"),override.slot||"portrait");
     assert.equal(form.get("profileSha256"),HASH);
     assert.equal(form.get("anchorSha256"),override.slot==="fullBody"?BODY:PORTRAIT);
     assert.match(form.get("requestKey"),/^AP008:(portrait|fullBody):[a-f0-9]{64}$/);
     assert.ok(form.get("image") instanceof File);
     return Response.json(override.upload||{assetId:"a08cb5a8-8b7e-45c0-a44c-4c9e5d7e5bb1",status:"awaiting_review"},{status:override.uploadStatus||201});
   }
   throw Error("Unexpected "+url);
 };
 return{calls,fetcher};
}
test("auto-submits genuine generated bytes with locked AP mapping and no extra clicks",async()=>{
 const {calls,fetcher}=stub();
 const result=await autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:await image("portrait")},{baseUrl:root,ownerToken:token,fetcher});
 assert.equal(result.status,"awaiting_review");assert.equal(result.stored,true);assert.equal(result.approved,false);
 assert.equal(calls.length,2);
});
test("fullBody uses its own anchor",async()=>{
 const {calls,fetcher}=stub({slot:"fullBody"});
 const result=await autoSubmitGeneratedImage({appearanceId:"AP008",slot:"fullBody",pngBytes:await image("fullBody")},{baseUrl:root,ownerToken:token,fetcher});
 assert.equal(result.slot,"fullBody");assert.equal(calls.length,2);
});
test("same image produces idempotent upload request key",async()=>{
 const bytes=await image("portrait");
 const keys=[];
 const fetcher=async(url,opt={})=>{
   if(!opt.method)return Response.json(profile);
   keys.push(opt.body.get("requestKey"));
   return Response.json({assetId:"a08cb5a8-8b7e-45c0-a44c-4c9e5d7e5bb1",status:"awaiting_review",duplicate:keys.length>1});
 };
 const params={baseUrl:root,ownerToken:token,fetcher};
 await autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:bytes},params);
 const r=await autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:bytes},params);
 assert.equal(keys[0],keys[1]);assert.equal(r.duplicate,true);
});
test("missing host bytes and bad identity fail before network",async()=>{
 const {calls,fetcher}=stub();
 await assert.rejects(()=>autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait"},{baseUrl:root,ownerToken:token,fetcher}),/not available/);
 await assert.rejects(()=>autoSubmitGeneratedImage({appearanceId:"APXYZ",slot:"portrait",pngBytes:await image("portrait")},{baseUrl:root,ownerToken:token,fetcher}),/locked AP/);
 assert.equal(calls.length,0);
});
test("unremoved background and wrong canvas are blocked",async()=>{
 const {calls,fetcher}=stub();
 await assert.rejects(()=>autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:await image("portrait","opaque")},{baseUrl:root,ownerToken:token,fetcher}),/Transparent background/);
 await assert.rejects(()=>autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:await image("portrait","magenta")},{baseUrl:root,ownerToken:token,fetcher}),/magenta/);
 await assert.rejects(()=>autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:await image("fullBody")},{baseUrl:root,ownerToken:token,fetcher}),/1024x1024/);
 assert.equal(calls.length,0);
});
test("unverified profile, server unavailable and missing upload acknowledgement do not claim success",async()=>{
 const bytes=await image("portrait");
 for(const v of [{getStatus:404},{profile:{...profile,profileSha256:"f".repeat(64)}},{uploadStatus:503},{upload:{ok:true}}]){
   const {fetcher}=stub(v);
   await assert.rejects(()=>autoSubmitGeneratedImage({appearanceId:"AP008",slot:"portrait",pngBytes:bytes},{baseUrl:root,ownerToken:token,fetcher}));
 }
});
