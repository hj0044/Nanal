import { createHash } from "node:crypto";
import path from "node:path";
import { readFile } from "node:fs/promises";
import { inspectPngBase64 } from "../chatgpt-import/validation.mjs";
import { immutableWrite } from "./import.mjs";

const AP_ID = /^AP[0-9]{3,5}$/;
const SHA256 = /^[a-f0-9]{64}$/i;
const REQUIRED_QA = [
  "faceIdentityPass",
  "heightScalePass",
  "bodyProfilePass",
  "chestSilhouettePass",
  "referencePairIdentityPass"
];

function stableJson(value) {
  if (Array.isArray(value)) return "[" + value.map(stableJson).join(",") + "]";
  if (value && typeof value === "object") {
    return "{" + Object.keys(value).sort().map(key =>
      JSON.stringify(key) + ":" + stableJson(value[key])
    ).join(",") + "}";
  }
  return JSON.stringify(value);
}

export function canonicalIdentitySha256(identity) {
  if (!identity || typeof identity !== "object" || Array.isArray(identity))
    throw Error("canonical_identity_object_required");
  return createHash("sha256").update(stableJson(identity), "utf8").digest("hex");
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function requireLockMatch(reservation, pack, appearanceId) {
  if (!reservation || reservation.appearanceId !== appearanceId ||
      reservation.status !== "approved" || !reservation.brief ||
      !reservation.images || !pack || pack.appearanceId !== appearanceId ||
      !pack.identity || !pack.identitySha256)
    throw Error("approved_canonical_reservation_and_asset_pack_required");

  const id = pack.identity;
  const brief = reservation.brief;
  const size = brief.physique || {};
  const pairs = [
    ["gender", brief.gender], ["ageBand", brief.ageBand],
    ["heightCm", brief.heightCm], ["weightKg", brief.weightKg],
    ["underbustCm", size.underbustCm], ["bustCm", size.bustCm],
    ["deltaCm", size.deltaCm], ["bustCup", brief.bustCup]
  ];
  for (const [field, value] of pairs) {
    if (value === undefined || id[field] !== value)
      throw Error("canonical_profile_mismatch:" + field);
  }
  const face = reservation.design?.faceDesign?.id || brief.faceDesign?.id;
  if (!face || id.faceDesign?.id !== face)
    throw Error("canonical_profile_mismatch:faceDesign");
  if (typeof id.bodyBuild !== "string" || !id.bodyBuild.trim())
    throw Error("canonical_profile_mismatch:bodyBuild");
  if (pack.identitySha256.toLowerCase() !== canonicalIdentitySha256(id))
    throw Error("canonical_profile_sha256_mismatch");
  if (reservation.designVersion && pack.designVersion !== reservation.designVersion)
    throw Error("canonical_design_version_mismatch");
}

function bytesOf(asset, role, reservation) {
  if (!asset || asset.role !== role || !asset.approved ||
      typeof asset.assetId !== "string" || !asset.assetId ||
      !SHA256.test(asset.sha256 || "") ||
      !Buffer.isBuffer(asset.png) ||
      !asset.png.length || asset.png.length > 16 * 1024 * 1024 ||
      !reservation.images?.[role] ||
      asset.sourcePath !== reservation.images[role])
    throw Error("canonical_anchor_bytes_unavailable:" + role);
  if (sha256(asset.png) !== asset.sha256.toLowerCase())
    throw Error("canonical_anchor_sha256_mismatch:" + role);
  return asset.png;
}

function checkReview(pack, appearanceId) {
  const q = pack.approvalEvidence;
  if (!q || q.appearanceId !== appearanceId ||
      REQUIRED_QA.some(field => q[field] !== true) ||
      typeof q.reviewer !== "string" || !q.reviewer.trim() ||
      typeof q.reviewedAt !== "string" ||
      !Number.isFinite(Date.parse(q.reviewedAt)) ||
      typeof q.notes !== "string" || q.notes.trim().length < 30 ||
      q.portraitSha256 !== pack.portrait.sha256 ||
      q.fullBodySha256 !== pack.fullBody.sha256)
    throw Error("canonical_visual_qa_incomplete");
}

/**
 * Only a trusted official Nanal connector adapter may return canonical PNG
 * Buffers. This routine NEVER fetches arbitrary URLs or guesses the host from
 * /api/appearance-files paths. Without a real official source it fails closed.
 *
 * The returned paths are local, private, immutable references for a subsequent
 * SAME-ID image edit. They are not proof that ChatGPT's image host can read
 * files or deliver generated bytes.
 */
export async function recoverCanonicalSource({
  appearanceId,
  privateRoot = ".nanal-private"
}, adapters = {}) {
  if (!AP_ID.test(appearanceId || "")) throw Error("valid_appearance_id_required");
  if (typeof adapters.getReservation !== "function" ||
      typeof adapters.getCanonicalAssets !== "function")
    throw Error("official_canonical_asset_read_action_not_exposed");

  const reservation = await adapters.getReservation({ appearanceId });
  const pack = await adapters.getCanonicalAssets({ appearanceId });
  requireLockMatch(reservation, pack, appearanceId);

  const portraitPng = bytesOf(pack.portrait, "portrait", reservation);
  const fullBodyPng = bytesOf(pack.fullBody, "fullBody", reservation);
  checkReview(pack, appearanceId);

  // CRC, PNG RGBA structure and dimensions: independent of the test adapter.
  inspectPngBase64(portraitPng.toString("base64"), { width: 1024, height: 1024 });
  inspectPngBase64(fullBodyPng.toString("base64"), { width: 1024, height: 1536 });
  const verifyPng = adapters.verifyPng || async (bytes, kind) => {
    const { preflightPng } = await import("./game-db-submit.mjs");
    return preflightPng(bytes, kind);
  };
  await verifyPng(portraitPng, "portrait");
  await verifyPng(fullBodyPng, "fullbody");

  const root = path.resolve(privateRoot, "canonical", appearanceId);
  const portraitPath = path.join(root, "portrait-" + pack.portrait.sha256 + ".png");
  const fullBodyPath = path.join(root, "fullbody-" + pack.fullBody.sha256 + ".png");
  await immutableWrite(portraitPath, portraitPng);
  await immutableWrite(fullBodyPath, fullBodyPng);

  // Read back after a write (or idempotent replay), not just a successful write.
  if (sha256(await readFile(portraitPath)) !== pack.portrait.sha256 ||
      sha256(await readFile(fullBodyPath)) !== pack.fullBody.sha256)
    throw Error("immutable_anchor_backup_integrity_failure");

  return {
    status: "ready_for_same_identity_variant_generation",
    appearanceId,
    identitySha256: pack.identitySha256,
    designVersion: pack.designVersion,
    portraitAnchor: {
      assetId: pack.portrait.assetId,
      sha256: pack.portrait.sha256,
      privatePath: portraitPath
    },
    fullBodyAnchor: {
      assetId: pack.fullBody.assetId,
      sha256: pack.fullBody.sha256,
      privatePath: fullBodyPath
    },
    qa: {
      reviewer: pack.approvalEvidence.reviewer,
      reviewedAt: pack.approvalEvidence.reviewedAt,
      reviewedSha256: [pack.portrait.sha256, pack.fullBody.sha256]
    },
    note: "Private reference pack only; no new generated images or game uploads claimed"
  };
}
